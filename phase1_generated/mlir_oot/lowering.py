def pack(bundle,**values):
    result=0
    for name,value in values.items():
        field=BUNDLES[bundle]['fields'][name]
        width=field.get('width') or field.get('slot_width')
        if width is None or not 0<=value<1<<width: raise ValueError('Field overflow '+bundle+'.'+name)
        result |= value << field['offset']
    return result

def fbits(x): return struct.unpack('<I',struct.pack('<f',float(x)))[0]

class Convert(RewritePattern):
    def __init__(self,source_ops=()):
        self.source_ops=set(source_ops)
    def match_and_rewrite(self,op,rewriter:PatternRewriter):
        if not op.name.startswith('merlin_iface.') and op not in self.source_ops: return
        attrs=dict(op.attributes);attrs['opcode']=StringAttr(op.name)
        replacement=DeviceOp(operands=[list(op.operands)],result_types=[list(op.result_types)],attributes=attrs)
        for old,new in zip(op.results,replacement.results): new.name_hint=old.name_hint
        rewriter.replace_op(op,replacement)

def lower(module):
    cb=inventory(module)
    if not any(op.name=='func.func' for op in module.body.block.ops):
        for index,op in enumerate(module.body.block.ops):
            if op.name.startswith('merlin_iface.') and op.name!='merlin_iface.tensor':
                op.attributes['merlin.source_op_index']=IntegerAttr(source_index(op,index),i64)
    indices={c['attributes']['merlin.source_op_index'] for c in cb['commands'] if 'merlin.source_op_index' in c.get('attributes',{})}
    # An extracted original owner may equal another operation's local index.
    # Indices establish ownership only after the source operation's semantics
    # have been proved; they must never turn setup, host work or a return into
    # a device region merely because its local position happens to match.
    source_ops=[op for fn in module.body.block.ops if fn.name=='func.func'
                for index,op in enumerate(fn.body.block.ops)
                if op.name in ('linalg.generic','linalg.matmul','linalg.batch_matmul')
                and signed_mac_body(op) and row_major_contraction(op)
                and source_index(op,index) in indices]
    for fn in module.body.block.ops:
        if fn.name=='func.func':
            for index,op in enumerate(fn.body.block.ops):
                if op in source_ops:op.attributes['merlin.source_op_index']=IntegerAttr(source_index(op,index),i64)
    PatternRewriteWalker(Convert(source_ops)).rewrite_module(module)
    module.verify()
    # CONV2D has a closed numerical-attribute vocabulary. Source ownership is
    # compiler metadata, so retain it in an indexed sidecar rather than expose
    # it as an unimplemented numerical parameter. The target IR and issued LLVM
    # commands still carry the exact original source attributes.
    for command_index,command in enumerate(cb['commands']):
        if command['opcode']!='CONV2D':continue
        owner={key:command['attributes'].pop(key) for key in ('merlin.source_op_index','prov.region_id') if key in command['attributes']}
        if owner:cb.setdefault('params',{}).setdefault('command_source_owners',{})[str(command_index)]=owner
    return cb,module

class Scheduler:
    def __init__(self,cb):
        self.cb=cb; self.ops=[]; self.source_attrs={}; self.readout_attrs=None; self.batch_strides={}; self.execution_config=None
        produced={c.get('operands',{}).get('dst') for c in cb['commands']}
        self.args=[n for n,t in cb['tensors'].items() if n not in produced and t.get('role') not in ('output','intermediate')]
        # The ordinary ABI publishes result pointers in command result order,
        # followed by any host-only outputs in tensor declaration order.
        published={'COMMIT','BIAS_ADD','RESIDUAL_ADD','ATTENTION_QK','ATTENTION_PV','CONV2D','BATCHED_MATMUL','MOVEMENT'}
        for command in cb['commands']:
            name=command.get('operands',{}).get('dst')
            if command['opcode'] in published and name in cb['tensors'] and name not in self.args:
                self.args.append(name)
        self.args += [n for n,t in cb['tensors'].items() if t.get('role')=='output' and n not in self.args]
        # The explicit ABI gives invocation-local storage to every materialized
        # tensor, including shared internal producers. Handles never occur in
        # tensors. No allocation is proportional to a resident device tile.
        self.args += [n for n in cb['tensors'] if n not in self.args]
        cb['compiler_pointer_abi']={'version':1,'arguments':self.args}
        if cb['commands']: cb.setdefault('params',{}).setdefault('lane_placement',[{'lane':'accelerator','reason':'Admitted i8 mesh and movement operations'}])
        # A pure device leaf uses the ordinary logical-pointer ABI. Its
        # commands describe all numerical work, and the default caller already
        # supplies the same input/output pointer order. Declare whole_program
        # only when invocation-local materialized graph tensors need pointers.
        if any(t.get('role')=='intermediate' or (n in produced and t.get('role')!='output') for n,t in cb['tensors'].items()):
            cb['kernel_abi']={'kind':'whole_program','args':[{'tensor':n,'access':'write' if cb['tensors'][n].get('role') in ('output','intermediate') or n in produced else 'read'} for n in self.args],'outputs':[n for n in self.args if cb['tensors'][n].get('role')=='output']}
    def issue(self,name,a=0,b=0):
        op=IssueOp(attributes={'instruction':StringAttr(name),'rs1':StringAttr(str(a)),'rs2':StringAttr(str(b)),**self.source_attrs})
        op.verify();self.ops.append(op)
    def configure_execution(self,rs1,rs2):
        """Track exact execution state within this emitted invocation.

        Load/store stream configuration and mesh commands preserve EX state.
        The entry state is unknown, so every invocation installs its first
        configuration. Equal consecutive regions reuse it; differing settings
        always issue a new write. This is compile-time state, never a cache
        shared across invocations or a suppression of data transfers.
        """
        state=(rs1,rs2)
        if self.execution_config!=state:
            self.issue('CONFIG_CMD',rs1,rs2)
            self.execution_config=state
    def issue_readout(self,name,a=0,b=0):
        owner=self.source_attrs
        if self.readout_attrs is not None:self.source_attrs=self.readout_attrs
        try:self.issue(name,a,b)
        finally:self.source_attrs=owner
    def address(self,name,offset=0,stride=0,kstride=0,nstride=0,tapstride=0):
        if name not in self.args: raise ValueError('Internal graph storage not implemented: '+name)
        return '@'+str(self.args.index(name))+':'+str(offset)+':'+str(stride)+':'+str(kstride)+':'+str(nstride)+':'+str(self.batch_strides.get(name,0))+':'+str(tapstride)
    def ld(self,stride,small=False,scale=1.0,state=0):
        self.issue('CONFIG_CMD',1|pack('ConfigMvinRs1',scale=fbits(scale),stride=DIM,shrink=int(small),state_id=state),stride)
    def st(self,stride,attrs):
        """Encode only selected readout stages, with their declared parameters.

        COMMIT/CONV2D apply the ordered epilogue. An unused scale attribute
        cannot change an identity readout; a selected scale has no implicit
        coefficient. Missing required parameters refuse before kernel emission.
        Geometry and field-width limits remain checked by the caller and pack.
        """
        stages=attrs.get('epilogue',[])
        scale=1.0
        if 'acc_scale' in stages:
            if 'acc_scale' not in attrs:
                raise ValueError('acc_scale stage requires an explicit coefficient')
            scale=attrs['acc_scale']
        fields={'cmd_type':2,'activation':int('relu' in stages)}
        if 'maxpool' in stages:
            h,w=attrs['pool_in_dims'];ph,pw=attrs['pool_size'];sh,sw=attrs['pool_stride'];pt,pl,pb,pr=attrs.get('pool_padding',[0,0,0,0])
            if ph!=pw or sh!=sw or attrs.get('pool_pad_value',0)!=0: raise ValueError('Store pooling requires square size/stride and zero padding value')
            oh=(h+pt+pb-ph)//sh+1;ow=(w+pl+pr-pw)//sw+1
            fields.update(pool_stride=sh,pool_size=ph,pool_out_dim=ow,porows=oh,pocols=ow,orows=h,ocols=w,upad=pt,lpad=pl)
        self.issue_readout('CONFIG_CMD',pack('ConfigMvoutRs1',**fields),pack('ConfigMvoutRs2',stride=stride,acc_scale=fbits(scale)))
    def choose_dataflow(self,m,k,n):
        return 1  # WS is legal for non-transposed static row-major i8 inputs.
    def check_tensor_domain(self):
        """Reject unknown extents before emitting target-visible work.

        The supported device ABI is static dense storage. Rank-zero tensors
        hold one element, as specified by the logical-pointer ABI and schema;
        every dimension of a ranked tensor must be strictly positive. Every byte
        offset is signed i64, and tiling may change device residency but cannot
        shrink the complete logical buffer. This is a domain refusal, never a
        truncation or a partially emitted command schedule.
        """
        widths={'i8':1,'i16':2,'i32':4,'i64':8,'f16':2,'bf16':2,'f32':4}
        for name,tensor in self.cb['tensors'].items():
            shape=tensor['shape']
            if any(type(d) is not int or d<=0 for d in shape):
                raise ValueError('Device tensor requires positive static extents: '+name)
            width=widths.get(tensor['dtype'])
            if width is None:
                raise ValueError('Device tensor storage width is unsupported: '+name)
            elements=math.prod(shape)
            if elements>((1<<63)-1)//width:
                raise ValueError('Device tensor byte extent exceeds signed RV64 addressing: '+name)
    def check_capacity(self):
        sp=next(m for m in HW['memories'] if m['name']=='scratchpad.mem')
        ac=next(m for m in HW['memory_address_spaces'] if m['name']=='accumulator')
        if 2*DIM*DIM>sp['bytes'] or DIM*DIM*4>ac['bytes']: raise ValueError('No legal tile fits')
    def movement(self,c):
        """Sign-extend the complete contiguous dense i8 buffer into i32 storage.

        Equal positive static shapes and full RV64 byte bounds are checked
        before scheduling. Flattening preserves linear element order because
        both pointer buffers are dense row-major and movement is elementwise.
        A fixed-pitch DIM-by-DIM tile overwrites one accumulator allocation;
        full blocks, remaining full rows and a final partial row cover disjoint
        byte intervals exactly once. Runtime loops bound emitted code size and
        allocation independently of tensor size, including long thin shapes.
        Fixed row pitches also avoid narrowing a large logical row stride into
        a hardware field. Unknown layouts/types/shapes refuse before emission.
        """
        o=c['operands'];src=self.cb['tensors'][o['src']];out=self.cb['tensors'][o['dst']]
        if src['dtype']!='i8' or out['dtype']!='i32': raise ValueError('Movement dtype outside implemented domain')
        if src['shape']!=out['shape']: raise ValueError('Movement must preserve logical extents')
        elements=math.prod(src['shape']);block=DIM*DIM
        self.ld(DIM,True);self.st(DIM*4,{})
        def tile(offset,rows,cols,dynamic=False):
            self.issue('LOAD_CMD',self.address(o['src'],offset,1 if dynamic else 0),pack('MvinRs2',local_addr=ACC,num_rows=rows,num_cols=cols))
            self.issue('STORE_CMD',self.address(o['dst'],offset*4,4 if dynamic else 0),pack('MvoutRs2',local_addr=ACC|FULL,num_rows=rows,num_cols=cols))
        full=elements//block*block
        self.tile_loop('m',0,full,block,lambda offset,dynamic:tile(offset,DIM,DIM,dynamic))
        remaining=elements-full;rows,cols=divmod(remaining,DIM)
        if rows:tile(full,rows,DIM)
        if cols:tile(full+rows*DIM,1,cols)
    def configure_contraction(self,m,k,n,size,attrs):
        """Install invariant execution/readout state before a matrix region.

        All batches of one checked contraction have the same shapes, dtypes,
        dataflow and epilogue. Neither PRELOAD nor COMPUTE changes the execution,
        readout or independent load-stream configuration.
        Separate RTL load states keep A and B row pitches invariant across
        the entire region. Bias uses a third independent stream. Hoisting
        these state writes preserves reduction order and all output descriptors. Independent operations configure their own state.
        """
        self.configure_execution(pack('ConfigExRs1',a_stride=1,dataflow=self.choose_dataflow(m,k,n),acc_scale=fbits(1.0)),pack('ConfigExRs2',c_stride=1))
        self.st(n*size,attrs)
        self.ld(k,state=0);self.ld(n,state=1)
        if any(stage in attrs.get('epilogue',[]) for stage in ('bias','bias_add')):
            self.ld(0,state=2)
    def contraction(self,a,b,y,attrs,dims=None,offsets=(0,0,0),acc_local=0,configure=True):
        at=self.cb['tensors'][a];bt=self.cb['tensors'][b];yt=self.cb['tensors'][y]
        if at['dtype']!='i8' or bt['dtype']!='i8' or (dims is None and (len(at['shape'])!=2 or len(bt['shape'])!=2)): raise ValueError('Contraction requires rank 2 i8')
        m,k=at['shape'][-2:];kk,n=bt['shape'][-2:]
        if dims is not None: m,k,n=dims;kk=k
        if k!=kk: raise ValueError('Contraction extent mismatch')
        if yt['dtype'] not in ('i8','i32'): raise ValueError('Contraction readout requires i8 or i32')
        stages=attrs.get('epilogue',[])
        if any(s not in ('bias_add','bias','relu','acc_scale','maxpool') for s in stages): raise ValueError('Unsupported epilogue '+str(stages))
        self.check_epilogue(attrs)
        expected_m=m
        if 'maxpool' in stages:
            h,w=attrs['pool_in_dims'];ph,pw=attrs['pool_size'];sh,sw=attrs['pool_stride'];pt,pl,pb,pr=attrs.get('pool_padding',[0,0,0,0])
            if min(h,w,ph,pw,sh,sw)<=0 or m%(h*w): raise ValueError('Invalid pooling geometry')
            expected_m=m//(h*w)*((h+pt+pb-ph)//sh+1)*((w+pl+pr-pw)//sw+1)
        if dims is None and yt['shape']!=[expected_m,n]: raise ValueError('Contraction output extent mismatch')
        if yt['dtype']=='i32' and any(s in ('relu','acc_scale','maxpool') for s in stages): raise ValueError('Full-width i32 readout applies no scale, relu or maxpool stage')
        size=4 if yt['dtype']=='i32' else 1
        bias=attrs.get('bias') if 'bias_add' in stages or 'bias' in stages else None
        if any(s in ('bias_add','bias') for s in stages):
            if bias not in self.cb['tensors'] or self.cb['tensors'][bias]['dtype']!='i32' or self.cb['tensors'][bias]['shape']!=[n]:
                raise ValueError('Bias seeding requires an i32 vector with N elements')
        if configure:
            self.configure_contraction(m,k,n,size,attrs)
        if 'maxpool' not in stages and ((m+DIM-1)//DIM)*((n+DIM-1)//DIM)*((k+DIM-1)//DIM)>64:
            return self.loop_contraction(a,b,y,attrs,m,k,n,size,bias,offsets,acc_local)
        pooling='maxpool' in stages
        spatial=m
        if pooling:
            h,w=attrs['pool_in_dims'];spatial=h*w
            if m%spatial or spatial>HW['memory_address_spaces'][0]['depth']*HW['memory_address_spaces'][0]['banks']:
                raise ValueError('Pooling spatial window exceeds resident accumulator allocation')
        for j in range(0,n,DIM):
            row_starts=(base+off for base in range(0,m,spatial) for off in range(0,spatial,DIM)) if pooling else range(0,m,DIM)
            for i in row_starts:
                rows=min(DIM,m-i,spatial-i%spatial) if pooling else min(DIM,m-i)
                cols=min(DIM,n-j)
                local=acc_local+(i%spatial if pooling else 0)
                if bias:
                    self.issue('LOAD3_CMD',self.address(bias,j*4),pack('MvinRs2',local_addr=ACC|local,num_rows=rows,num_cols=cols))
                for r in range(0,k,DIM):
                    depth=min(DIM,k-r)
                    self.issue('LOAD_CMD',self.address(a,offsets[0]+i*k+r),pack('MvinRs2',local_addr=0,num_rows=rows,num_cols=depth))
                    self.issue('LOAD2_CMD',self.address(b,offsets[1]+r*n+j),pack('MvinRs2',local_addr=DIM,num_rows=depth,num_cols=cols))
                    self.issue('PRELOAD_CMD',pack('PreloadRs',local_addr=DIM,num_rows=depth,num_cols=cols),pack('PreloadRs',local_addr=ACC|local|(ACCUM if r or bias else 0),num_rows=rows,num_cols=cols))
                    self.issue('COMPUTE_AND_FLIP_CMD',pack('ComputeRs',local_addr=0,num_rows=rows,num_cols=depth),pack('ComputeRs',local_addr=GARBAGE,num_rows=DIM,num_cols=DIM))
                if not pooling:
                    self.issue_readout('STORE_CMD',self.address(y,offsets[2]+(i*n+j)*size),pack('MvoutRs2',local_addr=ACC|local|(FULL if size==4 else 0),num_rows=rows,num_cols=cols))
                elif (i+rows)%spatial==0:
                    ph,pw=attrs['pool_size'];sh,sw=attrs['pool_stride'];pt,pl,pb,pr=attrs.get('pool_padding',[0,0,0,0])
                    pooled=((h+pt+pb-ph)//sh+1)*((w+pl+pr-pw)//sw+1)
                    outrow=(i//spatial)*pooled
                    self.issue_readout('STORE_CMD',self.address(y,offsets[2]+(outrow*n+j)*size),pack('MvoutRs2',local_addr=ACC,num_rows=0,num_cols=cols))
    def tile_loop(self,axis,start,upper,step,fn):
        if upper<=start:return
        if upper-start<=step:fn(start,False);return
        outer=self.ops;self.ops=[];fn(0,True);body=self.ops;self.ops=outer
        self.ops.append(TileLoopOp(attributes={'upper':IntegerAttr(upper,i64),'lower':IntegerAttr(start,i64),'axis':StringAttr(axis),'step':IntegerAttr(step,i64)},regions=[Region(Block(body,arg_types=[i64]))]))
    def loop_contraction(self,a,b,y,attrs,m,k,n,size,bias,offsets,acc_local=0):
        """Every M/N output tile owns all K slices; first slice resets, later slices accumulate."""
        def mtile(i,rows,md):
            def ntile(j,cols,nd):
                if bias:
                    self.issue('LOAD3_CMD',self.address(bias,j*4,nstride=4 if nd else 0),pack('MvinRs2',local_addr=ACC|acc_local,num_rows=rows,num_cols=cols))
                def ktile(r,depth,kd,accumulate):
                    self.issue('LOAD_CMD',self.address(a,offsets[0]+i*k+r,k if md else 0,1 if kd else 0),pack('MvinRs2',local_addr=0,num_rows=rows,num_cols=depth))
                    self.issue('LOAD2_CMD',self.address(b,offsets[1]+r*n+j,kstride=n if kd else 0,nstride=1 if nd else 0),pack('MvinRs2',local_addr=DIM,num_rows=depth,num_cols=cols))
                    self.issue('PRELOAD_CMD',pack('PreloadRs',local_addr=DIM,num_rows=depth,num_cols=cols),pack('PreloadRs',local_addr=ACC|acc_local|(ACCUM if accumulate else 0),num_rows=rows,num_cols=cols))
                    self.issue('COMPUTE_AND_FLIP_CMD',pack('ComputeRs',local_addr=0,num_rows=rows,num_cols=depth),pack('ComputeRs',local_addr=GARBAGE,num_rows=DIM,num_cols=DIM))
                ktile(0,min(k,DIM),False,bool(bias))
                full=k//DIM*DIM
                # Pair consecutive full K tiles to amortize host loop control.
                # Each still commits its own ordered partial sum. First-tile
                # seeding and a possible unmatched full tile/tail stay separate.
                paired_end=DIM+max(0,(full-DIM)//(2*DIM))*(2*DIM)
                def pair(r,kd):
                    ktile(r,DIM,kd,True)
                    ktile(r+DIM,DIM,kd,True)
                self.tile_loop('k',DIM,paired_end,2*DIM,pair)
                if full>paired_end:ktile(paired_end,DIM,False,True)
                if k>DIM and k>full:ktile(full,k-full,False,True)
                self.issue_readout('STORE_CMD',self.address(y,offsets[2]+(i*n+j)*size,n*size if md else 0,nstride=size if nd else 0),pack('MvoutRs2',local_addr=ACC|acc_local|(FULL if size==4 else 0),num_rows=rows,num_cols=cols))
            nf=n//DIM*DIM
            self.tile_loop('n',0,nf,DIM,lambda j,nd:ntile(j,DIM,nd))
            if n>nf:ntile(nf,n-nf,False)
        mf=m//DIM*DIM
        self.tile_loop('m',0,mf,DIM,lambda i,md:mtile(i,DIM,md))
        if m>mf:mtile(mf,m-mf,False)
    def conv_rhs_resident_allowed(self,k,n,tap_chunks):
        """Prove a one-N-tile packed RHS fits beside the fixed A tile.

        Dense KxN i8 source rows occupy K scratchpad rows of DIM i8 lanes.
        A owns [0,DIM); B owns [DIM,DIM+K). Bound the allocation to the first
        admitted physical bank, avoiding an assumed cross-bank address layout.
        Unknown geometry or descriptor limits select ordinary streaming.
        Residency is local to one region invocation; it never caches DRAM data.
        """
        if not (0<n<=DIM and 0<tap_chunks<=16 and k>0):return False
        memories=[m for m in HW.get('memories',[]) if m.get('name')=='scratchpad.mem']
        if len(memories)!=1:return False
        mem=memories[0]
        keys=('banks','depth','bytes','elem_bits','row_elems','row_bits_rtl')
        if any(type(mem.get(key)) is not int or mem[key]<=0 for key in keys):return False
        if mem['elem_bits']!=8 or mem['row_elems']!=DIM or mem['row_bits_rtl']!=DIM*8:return False
        row_bytes=mem['row_bits_rtl']//8
        if mem['bytes']!=mem['banks']*mem['depth']*row_bytes:return False
        # This conservative bank-local bound also proves the physical byte
        # allocation. Descriptor addresses must have every flag bit clear.
        if DIM+k>mem['depth'] or DIM+k>FULL:return False
        try:
            pack('MvinRs2',local_addr=DIM+k-1,num_rows=min(DIM,k),num_cols=n)
            pack('PreloadRs',local_addr=DIM+k-1,num_rows=min(DIM,k),num_cols=n)
        except (KeyError,TypeError,ValueError):return False
        return True
    def conv_input_resident_plan(self,a,batch,h,w,ci,kh,kw,n,sh,sw,dh,dw,pt,pl,pb,pr,oh,ow,k,channel_step,rhs_resident):
        """Admit a padded input canvas only when every physical row is proved.

        LocalAddr.scala assigns consecutive row-address bits to one bank and
        upper bits to the bank. Keep A in complete lower banks and place B at
        the beginning of the next bank: concurrent mesh reads never alias.
        The full-image path is intentionally optional; a shape that cannot fit
        still uses the existing bounded direct-DMA schedule.
        """
        if not rhs_resident or not 0<ci<=min(DIM,channel_step) or n>DIM:return None
        memories=[m for m in HW.get('memories',[]) if m.get('name')=='scratchpad.mem']
        if len(memories)!=1:return None
        mem=memories[0]
        banks,depth=mem.get('banks'),mem.get('depth')
        if any(type(x) is not int or x<=0 or x&(x-1) for x in (banks,depth)):return None
        if banks<2 or mem.get('row_bits_rtl')!=DIM*8 or mem.get('row_elems')!=DIM:
            return None
        if mem.get('bytes')!=banks*depth*DIM:return None
        canvas_h=h+pt+pb;canvas_w=w+pl+pr
        rows=batch*canvas_h*canvas_w
        if rows>(banks-1)*depth:return None
        b_base=((rows+depth-1)//depth)*depth
        if b_base+k>banks*depth or k>depth or b_base+k>=FULL:return None
        # Every DMA is split into at most DIM rows; the source's valid middle
        # segment and the zero-filled padding segments never cross provenance.
        ceil=lambda x:(x+DIM-1)//DIM
        sites=batch*((pt+pb)*ceil(canvas_w)+h*(ceil(pl)+ceil(w)+ceil(pr)))
        output_tiles=batch*oh*ceil(ow)
        # Canvas loading uses bounded CFG loops: sites counts dynamic DMA work,
        # not emitted instructions. Retain the reuse test and physical capacity
        # proof without excluding a legal canvas due to old static code growth.
        if output_tiles*kh*kw<2*sites:return None
        # Prove the last output/tap/mesh row is inside the canvas, including
        # non-unit stride and dilation. No runtime coordinate can exceed it.
        if (oh-1)*sh+(kh-1)*dh>=canvas_h or (ow-1)*sw+(kw-1)*dw>=canvas_w:
            return None
        try:
            pack('ConfigExRs1',a_stride=sw)
            pack('MvinRs2',local_addr=b_base+k-1,num_rows=DIM,num_cols=ci)
            pack('ComputeRs',local_addr=rows-1,num_rows=DIM,num_cols=ci)
        except (KeyError,TypeError,ValueError):return None
        return {'arg':self.args.index(a),
                'batch':batch,'h':h,'w':w,'ci':ci,'pt':pt,'pl':pl,'pb':pb,'pr':pr,
                'canvas_h':canvas_h,'canvas_w':canvas_w,'rows':rows,'b_base':b_base,
                'sites':sites,'bank_depth':depth}
    def conv_input_slab_plan(self,a,batch,h,w,ci,kh,kw,n,sh,sw,dh,dw,pt,pl,pb,pr,oh,ow,k,channel_step,rhs_resident):
        """Prove a complete one-output-row tap slab and disjoint resident RHS.

        The slab holds one padded width for each kernel-y tap. It is refreshed
        once per output row, including the upper/lower border rows, and reused
        across every output-x tile and kernel-x tap. Invalid source rows and
        horizontal padding read the compiler-owned zero row with stride zero.
        """
        if not rhs_resident or not 0<ci<=min(DIM,channel_step) or n>DIM:return None
        if any(v<=0 for v in (batch,h,w,kh,kw,sh,sw,dh,dw,oh,ow)) or any(v<0 for v in (pt,pl,pb,pr)):
            return None
        if batch*h*w*ci>=1<<63 or (oh-1)*sh+(kh-1)*dh>=1<<63 or pt>=1<<63:
            return None
        memories=[m for m in HW.get('memories',[]) if m.get('name')=='scratchpad.mem']
        if len(memories)!=1:return None
        mem=memories[0];banks,depth=mem.get('banks'),mem.get('depth')
        if any(type(v) is not int or v<=0 or v&(v-1) for v in (banks,depth)):return None
        if banks<2 or mem.get('row_bits_rtl')!=DIM*8 or mem.get('row_elems')!=DIM:
            return None
        if mem.get('bytes')!=banks*depth*DIM:return None
        width=w+pl+pr;rows=kh*width
        if rows>(banks-1)*depth:return None
        b_base=((rows+depth-1)//depth)*depth
        if b_base+k>banks*depth or k>depth or b_base+k>=FULL:return None
        ceil=lambda v:(v+DIM-1)//DIM
        sites=kh*(ceil(pl)+ceil(w)+ceil(pr))
        if sites>1024 or ceil(ow)*kh*kw<2*sites:return None
        if (ow-1)*sw+(kw-1)*dw>=width:return None
        try:
            pack('ConfigExRs1',a_stride=sw)
            pack('MvinRs2',local_addr=b_base+k-1,num_rows=DIM,num_cols=ci)
            pack('PreloadRs',local_addr=b_base+k-1,num_rows=DIM,num_cols=n)
            pack('ComputeRs',local_addr=rows-1,num_rows=DIM,num_cols=ci)
        except (KeyError,TypeError,ValueError):return None
        return {'arg':self.args.index(a),'h':h,'w':w,'ci':ci,'kh':kh,'kw':kw,
                'sh':sh,'sw':sw,'dh':dh,'dw':dw,'pt':pt,'pl':pl,'pb':pb,'pr':pr,
                'canvas_w':width,'rows':rows,'b_base':b_base,'sites':sites,
                'bank_depth':depth}
    def conv(self,c,residents):
        o=c['operands'];attrs=c['attributes'];a=o['ifm'];b=residents.get(o['weight'],o['weight']);y=o['dst']
        at,bt,yt=(self.cb['tensors'][v] for v in (a,b,y))
        if at['dtype']!='i8' or bt['dtype']!='i8' or attrs.get('layout','nhwc')!='nhwc':
            raise ValueError('Conv requires NHWC i8 input and packed i8 weights')
        batch,h,w,ci=at['shape'];kh,kw,kci,n=attrs['kernel']
        if ci!=kci or bt['shape']!=[kh*kw*ci,n]: raise ValueError('Conv weight extent mismatch')
        sh,sw=attrs.get('stride',[1,1]);dh,dw=attrs.get('dilation',[1,1])
        pt,pl,pb,pr=attrs.get('padding',[0,0,0,0])
        oh=(h+pt+pb-dh*(kh-1)-1)//sh+1;ow=(w+pl+pr-dw*(kw-1)-1)//sw+1
        m=batch*oh*ow;k=kh*kw*ci;size=4 if yt['dtype']=='i32' else 1
        if yt['shape']!=[m,n]: raise ValueError('Conv output shape mismatch or unsupported pooling')
        stages=attrs.get('epilogue',[])
        if any(t not in ('bias_add','bias','acc_scale','relu') for t in stages): raise ValueError('Unsupported conv epilogue')
        self.check_epilogue(attrs)
        if yt['dtype'] not in ('i8','i32'): raise ValueError('Conv readout requires i8 or i32')
        if size==4 and any(t in ('relu','acc_scale') for t in stages): raise ValueError('Full readout has no epilogue')
        bias=attrs.get('bias') if any(t in stages for t in ('bias','bias_add')) else None
        if any(t in stages for t in ('bias','bias_add')):
            if bias not in self.cb['tensors'] or self.cb['tensors'][bias]['dtype']!='i32' or self.cb['tensors'][bias]['shape']!=[n]:
                raise ValueError('Conv bias seeding requires an i32 vector with N elements')
        # A one-tap convolution still uses an ordered resident reduction.
        # With at least two channels, partition a short K into two productive
        # slices: the first seeds the tile and the next adds real products.
        # Mesh-sized and larger reductions retain their usual DIM slices.
        channel_step=min(DIM,(ci+1)//2) if kh*kw==1 and ci>1 else DIM
        tap_chunks=kh*kw*((ci+channel_step-1)//channel_step)
        # Copy-based im2col incurs scalar preparation proportional to the
        # reduction volume. Direct DMA preserves the same tap/channel order
        # without moving tensor values through the host. Small schedules fold
        # source geometry to constants; large schedules retain bounded loops.
        # This is a code-size limit, never a work or allocation limit.
        packed=False
        # Count the actual folded DMA groups before choosing specialization.
        # The finite work prefilter bounds compile time; the instruction cap
        # leaves room for configuration/fences under the public site budget.
        work=((m+DIM-1)//DIM)*((n+DIM-1)//DIM)*tap_chunks
        sites=4
        if work<=2048:
            for i in range(0,m,DIM):
                rows=min(DIM,m-i)
                tile_sites=1+int(bool(bias))
                for tap in range(kh*kw):
                    ky,kx=divmod(tap,kw)
                    offsets=[]
                    for row in range(rows):
                        bn,spatial=divmod(i+row,oh*ow);oy,ox=divmod(spatial,ow)
                        sy=oy*sh+ky*dh-pt;sx=ox*sw+kx*dw-pl
                        offsets.append(((bn*h+sy)*w+sx)*ci if 0<=sy<h and 0<=sx<w else None)
                    groups=0;row=0
                    while row<rows:
                        start=offsets[row];count=1
                        while row+count<rows and offsets[row+count]==(None if start is None else start+count*ci*sw):count+=1
                        groups+=1;row+=count
                    tile_sites+=(2*groups+3)*((ci+channel_step-1)//channel_step)
                sites+=tile_sites*((n+DIM-1)//DIM)
        static_geometry=work<=2048 and sites<=3800
        rhs_resident=self.conv_rhs_resident_allowed(k,n,tap_chunks)
        resident_input=None if static_geometry else self.conv_input_resident_plan(
            a,batch,h,w,ci,kh,kw,n,sh,sw,dh,dw,pt,pl,pb,pr,oh,ow,k,channel_step,rhs_resident)
        slab_input=None if static_geometry or resident_input else self.conv_input_slab_plan(
            a,batch,h,w,ci,kh,kw,n,sh,sw,dh,dw,pt,pl,pb,pr,oh,ow,k,channel_step,rhs_resident)
        residency=resident_input or slab_input
        # A horizontal kernel row is contiguous in NHWC when dilation_w=1.
        # Stage one DIM-row A tile after the resident canvas/slab, before the
        # separately banked RHS. Requiring sw=1 keeps the already configured
        # execution A stride identical for fused and border fallback tiles.
        stage_base=residency['rows'] if residency else 0
        horizontal_fusion=(not static_geometry and size==4 and not bias and
                           rhs_resident and sw==1 and dw==1 and kh<=16 and
                           kw*ci<=DIM and
                           (not residency or stage_base+DIM<=residency['b_base']))
        layout_record={
            'kind':'resident_input_canvas' if resident_input else 'resident_input_slab' if slab_input else 'direct_im2col_dma',
            'source':a,'geometry':'runtime' if not static_geometry else 'static',
            'reason':'capacity-proved on-device input reuse; ordered tap/channel reduction'
                     if residency else 'device-only value movement; ordered tap/channel reduction'}
        if residency:layout_record['scratchpad_rows']=residency['rows']
        if horizontal_fusion:
            layout_record['horizontal_fusion']={
                'kernel_row_depth':kw*ci,'a_stage_base':stage_base,
                'a_stage_rows':DIM,'interior_only':True}
        self.cb.setdefault('params',{}).setdefault('layout_lowering',[]).append(layout_record)
        self.configure_execution(pack('ConfigExRs1',a_stride=sw if residency else 1,dataflow=1,
                                      acc_scale=fbits(1)),pack('ConfigExRs2',c_stride=1))
        self.st(n*size,attrs)
        self.ld(n,state=1)
        if rhs_resident:
            # Each dense RHS row is transferred once for this source region.
            # Loads are <=DIM rows and remain disjoint from every A gather.
            rhs_base=residency['b_base'] if residency else DIM
            for r in range(0,k,DIM):
                self.issue('LOAD2_CMD',self.address(b,r*n),pack('MvinRs2',local_addr=rhs_base+r,num_rows=min(DIM,k-r),num_cols=n))
        if resident_input:
            self.ld(ci,state=0)
            self.ops.append(ResidentInputOp(attributes={'recipe':StringAttr(json.dumps(resident_input)),**self.source_attrs}))
        if bias:self.ld(0,state=2)
        if not static_geometry:
            return self.loop_conv(a,b,y,attrs,batch,h,w,ci,kh,kw,n,sh,sw,dh,dw,pt,pl,oh,ow,size,bias,channel_step,rhs_resident,resident_input,slab_input,horizontal_fusion,stage_base)
        def tile(i,rows,dynamic):
            for j in range(0,n,DIM):
                cols=min(DIM,n-j)
                if bias:
                    self.issue('LOAD3_CMD',self.address(bias,j*4),pack('MvinRs2',local_addr=ACC,num_rows=rows,num_cols=cols))
                chunks=((r,min(DIM,k-r)) for r in range(0,k,DIM)) if packed else ((tap*ci+channel,min(channel_step,ci-channel)) for tap in range(kh*kw) for channel in range(0,ci,channel_step))
                for r,depth in chunks:
                    recipe={'arg':self.args.index(a),'h':h,'w':w,'ci':ci,'kh':kh,'kw':kw,'oh':oh,'ow':ow,'sh':sh,'sw':sw,'dh':dh,'dw':dw,'pt':pt,'pl':pl,'i':i,'r':r,'rows':rows,'depth':depth,'dynamic':dynamic}
                    recipe['descriptors']=[pack('MvinRs2',local_addr=row,num_rows=1,num_cols=depth) for row in range(rows)]
                    recipe['packed']=packed
                    recipe['tile_descriptor']=pack('MvinRs2',local_addr=0,num_rows=rows,num_cols=depth)
                    self.ops.append(GatherOp(attributes={'recipe':StringAttr(json.dumps(recipe)),**self.source_attrs}))
                    if not rhs_resident:self.issue('LOAD2_CMD',self.address(b,r*n+j),pack('MvinRs2',local_addr=DIM,num_rows=depth,num_cols=cols))
                    self.issue('PRELOAD_CMD',pack('PreloadRs',local_addr=DIM+(r if rhs_resident else 0),num_rows=depth,num_cols=cols),pack('PreloadRs',local_addr=ACC|(ACCUM if r or bias else 0),num_rows=rows,num_cols=cols))
                    self.issue('COMPUTE_AND_FLIP_CMD',pack('ComputeRs',local_addr=0,num_rows=rows,num_cols=depth),pack('ComputeRs',local_addr=GARBAGE,num_rows=DIM,num_cols=DIM))
                self.issue('STORE_CMD',self.address(y,(i*n+j)*size,n*size if dynamic else 0),pack('MvoutRs2',local_addr=ACC|(FULL if size==4 else 0),num_rows=rows,num_cols=cols))
        full=m//DIM*DIM
        if static_geometry:
            for i in range(0,m,DIM):tile(i,min(DIM,m-i),False)
            return
        if full:
            outer=self.ops;self.ops=[];tile(0,DIM,True);body=self.ops;self.ops=outer
            self.ops.append(TileLoopOp(attributes={'upper':IntegerAttr(full,i64),'lower':IntegerAttr(0,i64),'axis':StringAttr('m'),'step':IntegerAttr(DIM,i64)},regions=[Region(Block(body,arg_types=[i64]))]))
        if m>full:tile(full,m-full,False)
    def loop_conv(self,a,b,y,attrs,batch,h,w,ci,kh,kw,n,sh,sw,dh,dw,pt,pl,oh,ow,size,bias,channel_step,rhs_resident,resident_input=None,slab_input=None,horizontal_fusion=False,stage_base=0):
        """Bounded row-aligned DMA schedule with complete ordered reduction.

        Spatial tiles never cross an output row. Interior bands prove every
        tap valid and use a single strided load; borders explicitly zero-pad.
        A tile origin is calculated once before its N/tap/channel reduction.
        Initial reduction resets (or uses bias); subsequent slices accumulate.
        One A tile, a proved bank-local resident RHS or one streaming B tile,
        and one accumulator tile bound live storage.
        Small tap reductions are folded under a fixed budget; larger K uses
        runtime tap/channel loops. All batch, spatial, channel and N tails
        remain present, with exactly one complete readout per output tile.
        """
        residency=resident_input or slab_input
        def spatial(bn,bd,oy,yd,ox,xd,rows,interior):
            origin={'arg':self.args.index(a),'h':h,'w':w,'ci':ci,'oh':oh,'ow':ow,
                    'sh':sh,'sw':sw,'pt':pt,'pl':pl,'batch':bn,'oy':oy,'ox':ox,
                    'batch_dynamic':bd,'y_dynamic':yd,'x_dynamic':xd}
            self.ops.append(TileOriginOp(attributes={'recipe':StringAttr(json.dumps(origin)),**self.source_attrs}))
            if interior and (not residency or horizontal_fusion):self.ld(ci*sw)
            def ntile(j,cols,nd):
                if bias:
                    self.issue('LOAD3_CMD',self.address(bias,j*4,nstride=4 if nd else 0),pack('MvinRs2',local_addr=ACC,num_rows=rows,num_cols=cols))
                if interior and horizontal_fusion:
                    # Each ky row is kw*ci consecutive i8 inputs. The source
                    # tile is wholly interior, so every DMA byte is in range.
                    # Flattened RHS rows ky*kw*ci..+kw*ci stay in K order.
                    depth=kw*ci
                    for ky in range(kh):
                        r=ky*depth
                        recipe={'arg':self.args.index(a),'h':h,'w':w,'ci':ci,
                                'sh':sh,'sw':sw,'dh':dh,'pt':pt,'pl':pl,
                                'ky':ky,'rows':rows,'depth':depth,
                                'horizontal_fusion':True,'local_addr':stage_base}
                        self.ops.append(GatherOp(attributes={'recipe':StringAttr(json.dumps(recipe)),**self.source_attrs}))
                        self.issue('PRELOAD_CMD',pack('PreloadRs',local_addr=residency['b_base']+r if residency else DIM+r,num_rows=depth,num_cols=cols),pack('PreloadRs',local_addr=ACC|(ACCUM if ky else 0),num_rows=rows,num_cols=cols))
                        self.issue('COMPUTE_AND_FLIP_CMD',pack('ComputeRs',local_addr=stage_base,num_rows=rows,num_cols=depth),pack('ComputeRs',local_addr=GARBAGE,num_rows=DIM,num_cols=DIM))
                    self.issue('STORE_CMD',self.address(y,j*size,n*size,nstride=size if nd else 0),pack('MvoutRs2',local_addr=ACC|FULL,num_rows=rows,num_cols=cols))
                    return
                def chunk(tap,channel,depth,td,kd,accumulate):
                    r=tap*ci+channel
                    recipe={'arg':self.args.index(a),'h':h,'w':w,'ci':ci,'kh':kh,'kw':kw,
                            'oh':oh,'ow':ow,'sh':sh,'sw':sw,'dh':dh,'dw':dw,'pt':pt,'pl':pl,
                            'i':0,'r':r,'rows':rows,'depth':depth,'dynamic':True,
                            'dynamic_tap':td,'dynamic_channel':kd,'packed':False,
                            'aligned_origin':True,'interior':interior,
                            'tile_descriptor':pack('MvinRs2',local_addr=0,num_rows=rows,num_cols=depth)}
                    if resident_input:
                        recipe['resident_input']={key:resident_input[key] for key in ('canvas_h','canvas_w','rows')}
                    if slab_input:
                        recipe['resident_slab']={key:slab_input[key] for key in ('canvas_w','rows')}
                    self.ops.append(GatherOp(attributes={'recipe':StringAttr(json.dumps(recipe)),**self.source_attrs}))
                    if not rhs_resident:self.issue('LOAD2_CMD',self.address(b,r*n+j,kstride=n if kd else 0,nstride=1 if nd else 0,tapstride=ci*n if td else 0),pack('MvinRs2',local_addr=DIM,num_rows=depth,num_cols=cols))
                    rhs_base=residency['b_base'] if residency else DIM
                    self.issue('PRELOAD_CMD',pack('PreloadRs',local_addr=rhs_base+(r if rhs_resident else 0),num_rows=depth,num_cols=cols),pack('PreloadRs',local_addr=ACC|(ACCUM if accumulate else 0),num_rows=rows,num_cols=cols))
                    self.issue('COMPUTE_AND_FLIP_CMD',pack('ComputeRs',local_addr=0,num_rows=rows,num_cols=depth),pack('ComputeRs',local_addr=GARBAGE,num_rows=DIM,num_cols=DIM))
                # Limit specialization independently of all spatial extents.
                if kh*kw*((ci+channel_step-1)//channel_step)<=16:
                    for tap in range(kh*kw):
                        for ch in range(0,ci,channel_step):chunk(tap,ch,min(channel_step,ci-ch),False,False,bool(tap or ch or bias))
                else:
                    full=ci//channel_step*channel_step
                    chunk(0,0,min(ci,channel_step),False,False,bool(bias))
                    self.tile_loop('k',channel_step,full,channel_step,lambda ch,kd:chunk(0,ch,channel_step,False,kd,True))
                    if ci>channel_step and ci>full:chunk(0,full,ci-full,False,False,True)
                    def tap_body(tap,td):
                        self.tile_loop('k',0,full,channel_step,lambda ch,kd:chunk(tap,ch,channel_step,td,kd,True))
                        if ci>full:chunk(tap,full,ci-full,td,False,True)
                    self.tile_loop('tap',1,kh*kw,1,tap_body)
                self.issue('STORE_CMD',self.address(y,j*size,n*size,nstride=size if nd else 0),pack('MvoutRs2',local_addr=ACC|(FULL if size==4 else 0),num_rows=rows,num_cols=cols))
            nf=n//DIM*DIM
            self.tile_loop('n',0,nf,DIM,lambda j,nd:ntile(j,DIM,nd))
            if n>nf:ntile(nf,n-nf,False)
        ceil=lambda a,b:-(-a//b)
        ylo=max(0,min(oh,ceil(pt,sh)))
        yhi=max(ylo,min(oh,ceil(h+pt-(kh-1)*dh,sh)))
        xlo=max(0,min(ow,ceil(pl,sw)))
        xhi=max(xlo,min(ow,ceil(w+pl-(kw-1)*dw,sw)))
        full=ow//DIM*DIM
        ilo=min(full,ceil(xlo,DIM)*DIM)
        ihi=max(ilo,min(full,xhi//DIM*DIM))
        def batch_body(bn,bd):
            def band(start,end,yinterior):
                def row_body(oy,yd):
                    if slab_input:
                        slab_recipe={**slab_input,'batch':bn,'batch_dynamic':bd,'oy':oy,'y_dynamic':yd}
                        self.ops.append(ResidentSlabOp(attributes={'recipe':StringAttr(json.dumps(slab_recipe)),**self.source_attrs}))
                    def col_range(lo,hi,interior):
                        self.tile_loop('ox',lo,hi,DIM,lambda ox,xd:spatial(bn,bd,oy,yd,ox,xd,DIM,interior))
                    col_range(0,ilo,False)
                    col_range(ilo,ihi,yinterior)
                    col_range(ihi,full,False)
                    if ow>full:spatial(bn,bd,oy,yd,full,False,ow-full,yinterior and full>=xlo and ow<=xhi)
                self.tile_loop('oy',start,end,1,row_body)
            band(0,ylo,False);band(ylo,yhi,True);band(yhi,oh,False)
        self.tile_loop('batch',0,batch,1,batch_body)

    def batched(self,c):
        """Alternate independent matrices between two bounded accumulator tiles.

        Every matrix owns its tile through all K slices and complete readout.
        A pair loop covers batch coordinates in original lexicographic order;
        an odd final matrix remains explicit. The two tiles fit the derived
        accumulator capacity. No allocation grows with the batch prefix.
        """
        o=c['operands'];a,b,y=o['a'],o['w'],o['dst']
        ash=self.cb['tensors'][a]['shape'];bsh=self.cb['tensors'][b]['shape']
        ysh=self.cb['tensors'][y]['shape']
        if len(ash)<3 or ash[:-2]!=bsh[:-2] or ash[:-2]!=ysh[:-2]:
            raise ValueError('Batched matmul requires identical static batch prefixes')
        m,k=ash[-2:];kk,n=bsh[-2:]
        if kk!=k or ysh[-2:]!=[m,n] or self.cb['tensors'][y]['dtype']!='i32':
            raise ValueError('Batched matmul shape/dtype mismatch')
        batch=1
        for d in ash[:-2]: batch*=d
        ac=next(space for space in HW['memory_address_spaces'] if space['name']=='accumulator')
        if batch>1 and 2*DIM*DIM*4>ac['bytes']:
            raise ValueError('Independent batch accumulator tiles exceed derived capacity')
        self.configure_contraction(m,k,n,4,c['attributes'])
        def one_batch(t,dynamic,acc_local):
            # Each independent matrix reconfigures execution and reuses the
            # two local accumulator tiles. Complete the preceding matrix's
            # readout before storage reuse, including on a batch backedge.
            self.ops.append(FenceOp(attributes=dict(self.source_attrs)))
            old=self.batch_strides
            self.batch_strides={a:m*k,b:k*n,y:m*n*4} if dynamic else {}
            try:self.contraction(a,b,y,c['attributes'],(m,k,n),(t*m*k,t*k*n,t*m*n*4),acc_local,configure=False)
            finally:self.batch_strides=old
        # Fold complete small batch schedules at compile time, using the same
        # source-derived work bound as the matrix scheduler. Larger prefixes
        # retain the bounded runtime batch loop and its full byte strides.
        tiles=((m+DIM-1)//DIM)*((k+DIM-1)//DIM)*((n+DIM-1)//DIM)
        if batch*tiles<=64:
            for t in range(batch):one_batch(t,False,(t%2)*DIM)
        else:
            paired=batch//2*2
            def pair(t,dynamic):
                one_batch(t,dynamic,0)
                one_batch(t+1,dynamic,DIM)
            self.tile_loop('batch',0,paired,2,pair)
            if batch>paired:one_batch(paired,False,0)
    def residual(self,c):
        """Scaled operand tiles sum through exact identity products on the mesh.

        Independent scratchpad load states retain both f32 scales for the
        complete operation. The lhs product overwrites before rhs accumulates;
        stores read only its live rows/columns, including both dimension tails.
        No tensor allocation or emitted instruction count grows with M/N.
        Non-saturating operand scales admit the declared one-LSB rounding bound;
        a zero bound is legal only when both scales are exact integer 0 or 1.
        """
        o=c['operands'];attrs=c['attributes']
        a,b,y=o['lhs'],o['rhs'],o['dst']
        ts=[self.cb['tensors'][v] for v in (a,b,y)]
        if any(t['dtype']!='i8' or t['shape']!=ts[0]['shape'] for t in ts):
            raise ValueError('Residual requires equal-shaped i8 tensors')
        shape=ts[0]['shape']
        if not shape or any(not isinstance(d,int) or d<=0 for d in shape):
            raise ValueError('Residual requires positive static tensor extents')
        scales=[]
        for key in ('lhs_scale','rhs_scale'):
            try:scale=struct.unpack('<f',struct.pack('<f',float(attrs[key])))[0]
            except (OverflowError,ValueError,TypeError):raise ValueError('Residual scale must be finite f32')
            # -128 * -1 is +128, outside i8. A negative scale needs the
            # stricter lower bound to keep both independently rounded inputs
            # unsaturated before their i32 sum.
            if not math.isfinite(scale) or not -127/128<=scale<=1:
                raise ValueError('Scaled load sum requires non-saturating finite operand scales')
            scales.append(scale)
        bound=attrs['bound_lsb']
        if not isinstance(bound,int) or bound<0 or (bound<1 and any(s not in (0.0,1.0) for s in scales)):
            raise ValueError('Scaled load sum requires bound_lsb >= 1 unless both operand scales are exact 0 or 1')
        if attrs.get('output_dtype','i8')!='i8': raise ValueError('Residual narrow readout requires i8 output')
        if any(s!='relu' for s in attrs.get('epilogue',[])): raise ValueError('Unsupported residual epilogue')
        self.check_epilogue(attrs)
        m=1;n=ts[0]['shape'][-1]
        for d in ts[0]['shape'][:-1]:m*=d
        # Scaled small loads into the accumulator diverged on native RTL.
        # Scale in the operand scratchpad path, then implement (A+B)I on the
        # mesh. Each product is x*1 or x*0, so the exact i32 reduction introduces
        # no additional rounding before the ordinary narrow readout.
        sp=next(mem for mem in HW['memories'] if mem['name']=='scratchpad.mem')
        if 3*DIM*DIM>sp['bytes']:raise ValueError('Residual identity schedule exceeds operand capacity')
        self.ops.append(IdentityTileOp(attributes=dict(self.source_attrs)))
        self.configure_execution(pack('ConfigExRs1',a_stride=1,dataflow=1,acc_scale=fbits(1)),pack('ConfigExRs2',c_stride=1))
        self.st(n,attrs)
        self.ld(n,False,scales[0],state=0)
        self.ld(n,False,scales[1],state=1)
        self.ld(DIM,False,1.0,state=2)
        self.issue('LOAD3_CMD','@i:0:0:0:0:0',pack('MvinRs2',local_addr=2*DIM,num_rows=DIM,num_cols=DIM))
        def tile(i,j,rows,cols,md=False,nd=False):
            for name,instruction,local in ((a,'LOAD_CMD',0),(b,'LOAD2_CMD',DIM)):
                self.issue(instruction,self.address(name,i*n+j,n if md else 0,nstride=1 if nd else 0),pack('MvinRs2',local_addr=local,num_rows=rows,num_cols=cols))
            for local,accumulate in ((0,False),(DIM,True)):
                self.issue('PRELOAD_CMD',pack('PreloadRs',local_addr=2*DIM,num_rows=cols,num_cols=cols),pack('PreloadRs',local_addr=ACC|(ACCUM if accumulate else 0),num_rows=rows,num_cols=cols))
                self.issue('COMPUTE_AND_FLIP_CMD',pack('ComputeRs',local_addr=local,num_rows=rows,num_cols=cols),pack('ComputeRs',local_addr=GARBAGE,num_rows=DIM,num_cols=DIM))
            self.issue('STORE_CMD',self.address(y,i*n+j,n if md else 0,nstride=1 if nd else 0),pack('MvoutRs2',local_addr=ACC,num_rows=rows,num_cols=cols))
        if ((m+DIM-1)//DIM)*((n+DIM-1)//DIM)<=64:
            for i in range(0,m,DIM):
                for j in range(0,n,DIM):tile(i,j,min(DIM,m-i),min(DIM,n-j))
            return
        def mtile(i,rows,md):
            nf=n//DIM*DIM
            self.tile_loop('n',0,nf,DIM,lambda j,nd:tile(i,j,rows,DIM,md,nd))
            if n>nf:tile(i,nf,rows,n-nf,md,False)
        mf=m//DIM*DIM
        self.tile_loop('m',0,mf,DIM,lambda i,md:mtile(i,DIM,md))
        if m>mf:mtile(mf,m-mf,False)
    def check_epilogue(self,attrs):
        """Hardware seeds bias before compute and scales before rectification.

        Repeated stages and other orderings require a separate proved transform;
        refuse them rather than silently replacing their source semantics.
        """
        stages=attrs.get('epilogue',[])
        if len(set(stages))!=len(stages) or ('bias' in stages and 'bias_add' in stages):
            raise ValueError('Repeated epilogue stage requires an explicit transform')
        order={'bias':0,'bias_add':0,'acc_scale':1,'relu':2,'maxpool':3}
        ranks=[order[s] for s in stages if s in order]
        if ranks!=sorted(ranks): raise ValueError('Epilogue order differs from admitted hardware pipeline')
    def schedule(self):
        if self.cb.get('declined') or self.cb.get('params',{}).get('provided_host_program'):return ModuleOp([])
        self.check_tensor_domain();self.check_capacity(); residents={};accumulators={}
        self.issue('FLUSH_CMD')
        for command_index,c in enumerate(self.cb['commands']):
            op=c['opcode'];o=c['operands']
            owner=dict(c['attributes'])
            owner.update(self.cb.get('params',{}).get('command_source_owners',{}).get(str(command_index),{}))
            self.source_attrs={key:IntegerAttr(value,i64) if isinstance(value,int) else StringAttr(value) for key,value in owner.items() if key in ('merlin.source_op_index','prov.region_id')}
            if op=='MATMUL': accumulators[o['dst']]=(o['lhs'],o['rhs'],dict(self.source_attrs))
            elif op=='RES_PACK': residents[o['dst']]=o['src']
            elif op=='MATMUL_RESIDENT': accumulators[o['dst']]=(o['lhs'],residents[o['rhs']],dict(self.source_attrs))
            elif op=='COMMIT':
                # Compute is deferred until readout geometry is known. Its owner
                # remains the actual contraction producer, even when COMMIT has
                # no source tags or belongs to a separately attributed epilogue.
                a,b,producer_attrs=accumulators[o['src']]
                self.readout_attrs=dict(self.source_attrs)
                self.source_attrs=producer_attrs
                try:self.contraction(a,b,o['dst'],c['attributes'])
                finally:self.readout_attrs=None
            elif op=='MOVEMENT': self.movement(c)
            elif op=='BATCHED_MATMUL': self.batched(c)
            elif op=='RESIDUAL_ADD': self.residual(c)
            elif op=='CONV2D': self.conv(c,residents)
            elif op=='EVICT': pass
            else: raise ValueError('Unsupported source opcode '+op)
        return ModuleOp(self.ops)
