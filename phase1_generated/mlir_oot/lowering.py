@irdl_op_definition
class DeviceOp(IRDLOperation):
    name='gemmini.region'
    inputs=var_operand_def()
    outputs=var_result_def()
    opcode=attr_def(StringAttr)
    def verify_(self):
        if not self.opcode.data: raise VerifyException('Missing source opcode')

@irdl_op_definition
class IssueOp(IRDLOperation):
    name='gemmini.issue'
    instruction=attr_def(StringAttr)
    rs1=attr_def(StringAttr)
    rs2=attr_def(StringAttr)
    def verify_(self):
        if self.instruction.data not in TEMPLATES: raise VerifyException('Unsupported command ISA')

@irdl_op_definition
class TileLoopOp(IRDLOperation):
    name='gemmini.tile_loop'
    upper=attr_def(IntegerAttr)
    lower=attr_def(IntegerAttr)
    axis=attr_def(StringAttr)
    step=attr_def(IntegerAttr)
    body=region_def()
    traits=traits_def(NoTerminator())
    def verify_(self):
        lower=self.lower.value.data;upper=self.upper.value.data;step=self.step.value.data
        if not 0<=lower<upper<1<<63 or not 0<step<1<<63:
            raise VerifyException('Invalid signed RV64 tile loop bounds')
        if self.axis.data not in ('m','k','n','batch','tap','oy','ox'):
            raise VerifyException('Unsupported tile loop axis')
        if len(self.body.blocks)!=1 or tuple(arg.type for arg in self.body.block.args)!=(i64,):
            raise VerifyException('Tile loop requires one i64 induction argument')

@irdl_op_definition
class GatherOp(IRDLOperation):
    name='gemmini.im2col_dma'
    recipe=attr_def(StringAttr)
    def verify_(self):
        x=json.loads(self.recipe.data)
        if not 0<x['rows']<=DIM or not 0<x['depth']<=DIM: raise VerifyException('Gather exceeds tile buffer')

@irdl_op_definition
class ResidentInputOp(IRDLOperation):
    """Load one source-derived padded NHWC canvas into device scratchpad."""
    name='gemmini.resident_input'
    recipe=attr_def(StringAttr)
    def verify_(self):
        x=json.loads(self.recipe.data)
        if not 0<x['ci']<=DIM or not 0<x['rows']<=x['b_base']:
            raise VerifyException('Resident input exceeds its proved scratchpad allocation')

@irdl_op_definition
class ResidentSlabOp(IRDLOperation):
    """Refresh one output row's tap rows in a bounded device slab."""
    name='gemmini.resident_input_slab'
    recipe=attr_def(StringAttr)
    def verify_(self):
        x=json.loads(self.recipe.data)
        if not 0<x['ci']<=DIM or not 0<x['rows']<=x['b_base'] or x['rows']!=x['kh']*x['canvas_w']:
            raise VerifyException('Resident slab exceeds its proved scratchpad allocation')

@irdl_op_definition
class TileOriginOp(IRDLOperation):
    """One source-derived horizontal output tile origin for direct DMA."""
    name='gemmini.tile_origin'
    recipe=attr_def(StringAttr)
    def verify_(self):
        x=json.loads(self.recipe.data)
        if any(x[k]<=0 for k in ('h','w','ci','oh','ow','sh','sw')):
            raise VerifyException('Invalid convolution origin geometry')

@irdl_op_definition
class IdentityTileOp(IRDLOperation):
    """Immutable i8 mesh-width identity, generated by a linearity rewrite.

    This compiler constant contains no source tensor values. Multiplication by
    it preserves each independently scaled scratchpad element exactly.
    """
    name='gemmini.identity_tile'

@irdl_op_definition
class FenceOp(IRDLOperation):
    """Complete an independent device operation before reconfiguration/reuse."""
    name='gemmini.fence'

